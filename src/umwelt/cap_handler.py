"""Capability-channel socket handler for Umwelt.

Per-use ephemeral UDS; line-JSON frames; five ops:
  snapshot:        {op, bytes:<b64>} → {ref:<cas:sha256:hex>}
  retrieve:        {op, ref:<cas:sha256:hex>} → {content:<b64>|null}
  advance_ref:     {op, capsule:<thing_id>, new_ref:<cas:...>, expected_ref:<cas:...|null>}
                   → {version:<int>, ref:<cas:...>} | {error:...}
  generate:        {op, render_spec:<dict>} → {job_id:<str>} | {status:..., spec_key:...}
  generate_status: {op, job_id:<str>} → {status:...}

Schema-strict: snapshot accepts ONLY {op, bytes}; retrieve ONLY {op, ref};
advance_ref ONLY {op, capsule, new_ref, expected_ref}; generate ONLY {op,
render_spec}; generate_status ONLY {op, job_id}. Any extra/unknown field
(e.g. source/path/url) → {error:…} before dispatch — the confused-deputy
reach-around is impossible by construction because there is NO fetch
codepath in this handler (Borges, forum #199 #3801, ob_0910).

advance_ref (umwelt #186, docs/CAPABILITY-CHANNEL.md's cross-owner-verb
design rule) is the first cross-owner-able capability — it ships WITH its
gate: `thing.author == caller`, where `caller` is the agent that invoked the
`use()` spawning this UDS (never a caller-asserted field on the frame itself
— see CapHandler.__init__). See db.advance_capsule_ref for the full
compare-and-swap + provenance-log semantics; this handler only validates the
frame shape and rate-caps before delegating.

generate/generate_status (umwelt#464 slice 2, the `generate` capability-
channel op) — a scroll/tool running inside `use()` can request new
AI-generated sprite art via the standalone art-gen service. `generate`
returns in milliseconds regardless of how long the underlying generation
takes: it spawns a daemon background thread (NOT joined, NOT tied to
stop()/_shutdown — it must outlive this CapHandler instance, since `use()`
has a 30s ceiling and generation can take up to ~14 minutes cold) and
returns a `job_id` immediately; `generate_status` polls that job by id.
STAGE-ONLY: this module only ever quarantines generated bytes into the
sprite_dir's pending-staging store and records a `pending` manifest entry
(`webrender.manifest.add_pending`) — it never promotes anything to `live`.
`webrender.manifest`'s live-promotion function is a DIFFERENT agent's peer
review, deliberately never imported here — see _op_generate's docstring.

Resource caps (Ariadne, forum #199 #3819):
  - 8 MiB per blob
  - 128 requests / use
  - 8 concurrent connections / use
  - 256 MiB total stored / use
  - 16 advance_ref advances / use (umwelt #186 v2 spec comment — mirrors the
    snapshot rate-cap shape: a scroll must not churn a capsule as DoS)

generate/generate_status have no dedicated rate cap of their own beyond the
shared _MAX_REQUESTS_PER_USE — a generate call is gated far more expensively
by the idempotency-before-generation check (below) and the art-gen service's
own quota, not by a per-use counter here. That idempotency check is a
per-request guarantee, not a cross-request lock: two near-simultaneous
`generate` calls for the identical render_spec (from two different `use()`
invocations) can both pass the check before either background job records a
manifest entry, so both would call the art-gen service and insert a
generate_jobs row for the same spec_key. `manifest.add_pending`'s own
idempotency still prevents a duplicate manifest entry — this is a
wasted-GPU-call/duplicate-job-row cost, not a correctness or security gap.

Design: docs/CAPABILITY-CHANNEL.md (commit 707f40d).
"""

from __future__ import annotations

import base64
import json
import sqlite3
import socket
import threading
import uuid
from pathlib import Path

from . import cas, db
from ._ids import canonical_agent

# Resource caps pinned by Ariadne (forum #199 #3819).
_BLOB_SIZE_CAP = 8 * 1024 * 1024              # 8 MiB per blob
_MAX_REQUESTS_PER_USE = 128                    # total frames this use
_MAX_CONNECTIONS_PER_USE = 8                   # concurrent connections
_MAX_TOTAL_BYTES_PER_USE = 256 * 1024 * 1024  # 256 MiB total stored per use
_MAX_ADVANCES_PER_USE = 16                     # advance_ref calls this use (umwelt #186)

# Max raw bytes buffered waiting for a newline. base64(8MiB) ≈ 10.7MiB; add
# JSON envelope headroom. If exceeded the connection is closed (not an error
# reply, because the frame is truncated/malformed anyway).
_MAX_FRAME_BYTES = _BLOB_SIZE_CAP * 2

# Strict allow-lists per op — reject-unknown-keys (not permissive-ignore-extras).
# This is what makes fixture (a) "impossible by construction": snapshot has no
# fetch codepath, and any field that would hint at one is a schema error.
_SNAPSHOT_KEYS = frozenset({"op", "bytes"})
_RETRIEVE_KEYS = frozenset({"op", "ref"})
_ADVANCE_REF_KEYS = frozenset({"op", "capsule", "new_ref", "expected_ref"})
_GENERATE_KEYS = frozenset({"op", "render_spec"})
_GENERATE_STATUS_KEYS = frozenset({"op", "job_id"})


def _err(msg: str) -> bytes:
    return (json.dumps({"error": msg}) + "\n").encode()


def _ok(data: dict) -> bytes:
    return (json.dumps(data) + "\n").encode()


class CapHandler:
    """Capability-channel socket handler — one instance per `use` invocation.

    Call start() before the sandbox process launches, stop() after it exits.
    Thread-safe: all shared counters are guarded by _lock.
    """

    def __init__(self, sock_path: str, db_path: str,
                 caller: str | None = None,
                 sprite_dir: str | Path | None = None,
                 art_service_url: str | None = None) -> None:
        """`caller` (umwelt #186) is the agent identity of the `use()` that
        spawned this UDS — threaded in from run_thing_capped, which gets it
        from server.py's already-in-scope `agent` var at the ONE
        run_thing_capped call site. This is the ONLY source of caller
        identity advance_ref's owner gate trusts: a frame can never assert
        its own caller (there is no such field in _ADVANCE_REF_KEYS) — the
        gate is structurally free of caller-supplied metadata, per
        docs/CAPABILITY-CHANNEL.md's cross-owner-verb design rule.

        `sprite_dir`/`art_service_url` (umwelt#464 slice 2) gate the
        generate/generate_status ops — both `None` (the default) means
        generation is not configured on this engine, and `_op_generate`
        refuses immediately rather than attempting anything. There is no
        `tier_config` param here: the tier-binding checks (does this
        engine's --db match the tier-config's db? does the sprite_dir's own
        marker match the tier?) happen ONCE at engine boot, in server.py —
        by the time a CapHandler is constructed, `sprite_dir` is already
        either verified-safe or `None`.
        """
        self._sock_path = sock_path
        self._db_path = db_path
        self._caller = caller
        self._sprite_dir = sprite_dir
        self._art_service_url = art_service_url
        self._lock = threading.Lock()
        self._request_count = 0
        self._total_bytes_stored = 0
        self._advance_count = 0
        self._conn_count = 0
        self._server_sock: socket.socket | None = None
        self._thread: threading.Thread | None = None
        self._shutdown = threading.Event()

    def start(self) -> None:
        """Bind the UDS, start listening, accept connections in a daemon thread."""
        sock_path = Path(self._sock_path)
        sock_path.parent.mkdir(parents=True, exist_ok=True)
        if sock_path.exists():
            sock_path.unlink()

        self._server_sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self._server_sock.bind(self._sock_path)
        self._server_sock.listen(_MAX_CONNECTIONS_PER_USE)
        self._server_sock.settimeout(0.5)  # lets accept() wake up to check _shutdown

        self._thread = threading.Thread(target=self._accept_loop, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        """Signal shutdown, close the server socket, wait for the accept thread."""
        self._shutdown.set()
        if self._server_sock is not None:
            try:
                self._server_sock.close()
            except OSError:
                pass
        if self._thread is not None:
            self._thread.join(timeout=5)
        try:
            Path(self._sock_path).unlink(missing_ok=True)
        except OSError:
            pass

    # ------------------------------------------------------------------
    # Internal: accept loop and per-connection handler
    # ------------------------------------------------------------------

    def _accept_loop(self) -> None:
        while not self._shutdown.is_set():
            try:
                conn, _ = self._server_sock.accept()
            except (socket.timeout, OSError):
                continue

            with self._lock:
                if self._conn_count >= _MAX_CONNECTIONS_PER_USE:
                    try:
                        conn.sendall(_err("rate limit: too many concurrent connections"))
                        conn.close()
                    except OSError:
                        pass
                    continue
                self._conn_count += 1

            t = threading.Thread(
                target=self._handle_conn, args=(conn,), daemon=True
            )
            t.start()

    def _handle_conn(self, conn: socket.socket) -> None:
        buf = b""
        try:
            while not self._shutdown.is_set():
                try:
                    chunk = conn.recv(65536)
                except OSError:
                    break
                if not chunk:
                    break
                buf += chunk
                # Guard against a frame that never sends a newline.
                if len(buf) > _MAX_FRAME_BYTES:
                    try:
                        conn.sendall(_err("frame too large"))
                    except OSError:
                        pass
                    return
                while b"\n" in buf:
                    line, buf = buf.split(b"\n", 1)
                    if not line.strip():
                        continue
                    response = self._dispatch(line)
                    try:
                        conn.sendall(response)
                    except OSError:
                        return
        finally:
            with self._lock:
                self._conn_count -= 1
            try:
                conn.close()
            except OSError:
                pass

    def _dispatch(self, line: bytes) -> bytes:
        # Request counter — checked before any work.
        with self._lock:
            if self._request_count >= _MAX_REQUESTS_PER_USE:
                return _err("rate limit: max requests per use exceeded")
            self._request_count += 1

        # Parse — a parse error returns an error response; the handler stays up.
        try:
            frame = json.loads(line.decode("utf-8", errors="replace"))
        except Exception:
            return _err("malformed frame: not valid JSON")

        if not isinstance(frame, dict):
            return _err("malformed frame: expected JSON object")

        op = frame.get("op")
        if op == "snapshot":
            return self._op_snapshot(frame)
        if op == "retrieve":
            return self._op_retrieve(frame)
        if op == "advance_ref":
            return self._op_advance_ref(frame)
        if op == "generate":
            return self._op_generate(frame)
        if op == "generate_status":
            return self._op_generate_status(frame)
        if op is None:
            return _err("malformed frame: missing op")
        return _err(f"unknown op: {op!r}")

    def _op_snapshot(self, frame: dict) -> bytes:
        # Schema-strict: ONLY {op, bytes} allowed. Any extra key is a schema
        # rejection — not a runtime dispatch error. This means a frame carrying
        # source/path/url/forum: never reaches any fetch path, because there is
        # no fetch path: the rejection happens before dispatch even looks at
        # the value (Borges, ob_0910 — confused-deputy closure by construction).
        extra = set(frame.keys()) - _SNAPSHOT_KEYS
        if extra:
            return _err(f"unexpected fields in snapshot: {sorted(extra)!r}")

        b64 = frame.get("bytes")
        if b64 is None:
            return _err("snapshot requires bytes field")
        if not isinstance(b64, str):
            return _err("snapshot.bytes must be a base64 string")

        try:
            content = base64.b64decode(b64, validate=True)
        except Exception:
            return _err("snapshot.bytes: invalid base64")

        n = len(content)
        if n > _BLOB_SIZE_CAP:
            return _err(
                f"snapshot.bytes too large: {n} bytes > {_BLOB_SIZE_CAP} cap"
            )

        # Total-bytes quota: charge before store (conservative; if store fails,
        # the quota is spent — avoids an attacker exploiting repeated failures).
        with self._lock:
            if self._total_bytes_stored + n > _MAX_TOTAL_BYTES_PER_USE:
                return _err("rate limit: total bytes per use exceeded")
            self._total_bytes_stored += n

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                ref = cas.store(conn, self._db_path, content)
            finally:
                conn.close()
        except Exception as exc:
            return _err(f"store failed: {exc}")

        return _ok({"ref": ref})

    def _op_retrieve(self, frame: dict) -> bytes:
        # Schema-strict: ONLY {op, ref} allowed.
        extra = set(frame.keys()) - _RETRIEVE_KEYS
        if extra:
            return _err(f"unexpected fields in retrieve: {sorted(extra)!r}")

        ref = frame.get("ref")
        if ref is None:
            return _err("retrieve requires ref field")
        if not isinstance(ref, str):
            return _err("retrieve.ref must be a string")

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                content = cas.retrieve(conn, self._db_path, ref)
            finally:
                conn.close()
        except Exception as exc:
            return _err(f"retrieve failed: {exc}")

        if content is None:
            return _ok({"content": None})
        return _ok({"content": base64.b64encode(content).decode()})

    def _op_advance_ref(self, frame: dict) -> bytes:
        # Schema-strict: ONLY {op, capsule, new_ref, expected_ref} allowed —
        # same reject-unknown-keys posture as snapshot/retrieve.
        extra = set(frame.keys()) - _ADVANCE_REF_KEYS
        if extra:
            return _err(f"unexpected fields in advance_ref: {sorted(extra)!r}")

        capsule = frame.get("capsule")
        if capsule is None:
            return _err("advance_ref requires capsule field")
        if not isinstance(capsule, str):
            return _err("advance_ref.capsule must be a string")

        new_ref = frame.get("new_ref")
        if new_ref is None:
            return _err("advance_ref requires new_ref field")
        if not isinstance(new_ref, str):
            return _err("advance_ref.new_ref must be a string")

        # expected_ref is REQUIRED as a key (null is a valid VALUE, for the
        # first-ever advance) — so its absence is a schema error distinct
        # from an explicit null, same tri-state discipline server.py uses
        # elsewhere for patch semantics.
        if "expected_ref" not in frame:
            return _err("advance_ref requires expected_ref field (string or null)")
        expected_ref = frame.get("expected_ref")
        if expected_ref is not None and not isinstance(expected_ref, str):
            return _err("advance_ref.expected_ref must be a string or null")

        # Rate cap (umwelt #186 v2 spec comment) — mirrors the snapshot
        # total-bytes-per-use shape: check-and-charge under the lock, before
        # any DB work, so a flood can't slip extra advances through a race.
        with self._lock:
            if self._advance_count >= _MAX_ADVANCES_PER_USE:
                return _err("rate limit: max advances per use exceeded")
            self._advance_count += 1

        # Phantom-ref reject: new_ref must already be a well-formed,
        # already-stored CAS ref — never point a capsule at an absent blob.
        hexhash = cas.parse_ref(new_ref)
        if hexhash is None:
            return _err(
                "advance_ref.new_ref must be a well-formed cas:sha256:<hex> ref")

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                row = conn.execute(
                    "SELECT hash FROM cas_entries WHERE hash = ?", (hexhash,)
                ).fetchone()
                if row is None:
                    return _err(
                        f"advance_ref.new_ref {new_ref!r} does not exist in "
                        "CAS — phantom ref rejected")

                try:
                    new_version, ref = db.advance_capsule_ref(
                        conn, capsule, self._caller, new_ref, expected_ref)
                except ValueError as exc:
                    return _err(str(exc))
            finally:
                conn.close()
        except Exception as exc:
            return _err(f"advance_ref failed: {exc}")

        return _ok({"version": new_version, "ref": ref})

    def _op_generate(self, frame: dict) -> bytes:
        """Requests new AI-generated sprite art for `render_spec` (umwelt#464
        slice 2). STAGE-ONLY — this method (and everything it calls) never
        promotes anything to `live`; see the module docstring.

        Returns almost instantly regardless of generation latency: either an
        immediate idempotent hit (an existing manifest entry for this spec's
        key, in ANY status), or a `job_id` for a freshly spawned background
        generation thread (never joined, never tied to stop()/_shutdown — it
        must outlive this CapHandler instance, since `use()` has a 30s
        ceiling and generation can take up to ~14 minutes cold).
        """
        # Schema-strict: ONLY {op, render_spec} allowed — same reject-
        # unknown-keys posture as every other op in this handler.
        extra = set(frame.keys()) - _GENERATE_KEYS
        if extra:
            return _err(f"unexpected fields in generate: {sorted(extra)!r}")

        # Graceful-degrade: an engine that booted without a valid
        # --tier-config (server.py's job, not this handler's) has both of
        # these as None — never attempt anything else in that case.
        if self._sprite_dir is None or self._art_service_url is None:
            return _err("art generation not configured on this engine")

        render_spec = frame.get("render_spec")
        if render_spec is None:
            return _err("generate requires render_spec field")
        if not isinstance(render_spec, dict):
            return _err("generate.render_spec must be an object")

        # Imported by name, individually, and lazily (only reached once
        # generation is actually configured — see the None-check above) —
        # deliberately NOT `import ... manifest` as a whole, and NEVER
        # anything from manifest's live-promotion path: that path is a
        # DIFFERENT agent's peer review, and must stay genuinely
        # unimportable-by-accident from this module (an ImportError if
        # anyone ever tries, not merely "uncalled by convention").
        from .webrender.manifest import add_pending, list_entries
        from .webrender.sprites import spec_key

        key = spec_key(render_spec)

        # Idempotency-before-generation (mirrors gateway.py's
        # library_generate route, gateway.py:2119-2121 — checked BEFORE
        # spawning any job/thread/GPU call): an existing manifest entry in
        # ANY status means someone already requested/curated this exact
        # spec — no job row, no thread, no GPU call.
        for entry in list_entries(self._sprite_dir):
            if entry.get("spec_key") == key:
                return _ok({"status": entry.get("status"), "spec_key": key})

        job_id = uuid.uuid4().hex
        # `self._caller` is already folded upstream (run_thing_capped's own
        # docstring), but fold again here anyway — cheap, and matches this
        # module's "route every fold through canonical_agent" discipline.
        caller = canonical_agent(self._caller)

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                db.insert_generate_job(conn, job_id, caller, key, render_spec)
            finally:
                conn.close()
        except Exception as exc:
            return _err(f"failed to record generate job: {exc}")

        # Background thread — NOT part of request/response flow, not
        # joined, outlives this CapHandler instance by design (see this
        # method's own docstring).
        threading.Thread(
            target=self._run_generate_job,
            args=(job_id, key, render_spec, caller),
            daemon=True,
        ).start()

        return _ok({"job_id": job_id})

    def _run_generate_job(self, job_id: str, spec_key_val: str,
                           render_spec: dict, caller: str) -> None:
        """Runs in the background thread spawned by `_op_generate` — NOT
        part of request/response flow, returns nothing. Any exception
        raised here has no caller to propagate to (this thread outlives the
        request that spawned it), so every step past the initial status
        write is wrapped: an exception must never escape this method
        uncaught, on pain of a silently-hung background thread.
        """
        try:
            conn = sqlite3.connect(self._db_path)
            try:
                db.update_generate_job_status(conn, job_id, "running")
            finally:
                conn.close()
        except Exception:
            pass  # best-effort — the final status write below still runs

        status = "error"
        result: dict = {"error": "generate job did not complete"}

        # Imported lazily (same rationale as _op_generate's own imports),
        # and inside its own guarded try — same posture as the generation
        # block below, on pain of this method's own docstring promise: an
        # import failure here must still reach the final status write, not
        # leave the job stuck at "running" forever (generate_jobs_due_gc
        # deliberately never sweeps queued/running rows, so there is no
        # self-healing path if this escaped uncaught).
        try:
            from .webrender.manifest import add_pending
            from .webrender.model_renderer import GenerationUnavailable, ImageModelRenderer
            from .webrender.sprites import SpriteStore, derive_seed
        except Exception as e:
            result = {"error": f"generate job setup failed: {e}"}
        else:
            try:
                # umwelt#476: shared with gateway.py's library_generate via
                # sprites.derive_seed, not inlined here.
                seed = derive_seed(spec_key_val)
                # umwelt#472: ImageModelRenderer's own default (60s) is
                # shorter than the art service's (internal tooling, not in this release) worst-case response time (up
                # to GENERATION_QUEUE_TIMEOUT_S=120s waiting for the
                # concurrency slot, plus a cold generation measured at
                # ~215s in production) -- the default would defeat this
                # background thread's whole reason for existing (tolerating
                # a wait use()'s 30s ceiling can't). Server-to-server, no
                # human waiting synchronously on it, so a generous timeout
                # costs nothing here.
                renderer = ImageModelRenderer(
                    self._art_service_url, caller, timeout=1000.0)
                raw = renderer.generate(render_spec, seed)

                # Stage bytes BEFORE recording the manifest row (gateway.py:
                # 2141-2142/:2155's exact ordering) — a manifest row must
                # never exist without its bytes already staged.
                SpriteStore(Path(self._sprite_dir) / ".pending").put(spec_key_val, raw)
                entry = add_pending(self._sprite_dir, spec_key_val, render_spec, caller)
                status, result = "done", entry
            except GenerationUnavailable as e:
                status, result = "error", {"error": str(e)}
            except Exception as e:
                # Defensive: this runs off-thread with nothing to catch it —
                # an exception here must never crash the process or hang
                # silently.
                status, result = "error", {"error": str(e)}

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                db.update_generate_job_status(conn, job_id, status, result=result)
            finally:
                conn.close()
        except Exception:
            pass  # best-effort — nothing further to do if this write fails

    def _op_generate_status(self, frame: dict) -> bytes:
        """Polls a prior `generate` call by `job_id` (umwelt#464 slice 2).

        Owner gate — identity-based, not secret-based, the security-
        critical line of this op: a job that doesn't exist and a job that
        exists but belongs to a DIFFERENT caller return the exact same
        `{"status": "not_found"}` shape. `job_id` must never become an
        existence oracle for another agent's generation request.
        """
        # Schema-strict: ONLY {op, job_id} allowed.
        extra = set(frame.keys()) - _GENERATE_STATUS_KEYS
        if extra:
            return _err(f"unexpected fields in generate_status: {sorted(extra)!r}")

        job_id = frame.get("job_id")
        if job_id is None:
            return _err("generate_status requires job_id field")
        if not isinstance(job_id, str):
            return _err("generate_status.job_id must be a string")

        try:
            conn = sqlite3.connect(self._db_path)
            try:
                row = db.get_generate_job(conn, job_id)
            finally:
                conn.close()
        except Exception as exc:
            return _err(f"generate_status lookup failed: {exc}")

        # Owner gate: see this method's own docstring — both branches below
        # return the identical reply shape.
        if row is None or row["caller"] != canonical_agent(self._caller):
            return _ok({"status": "not_found"})

        status = row["status"]
        if status in ("queued", "running"):
            return _ok({"status": status})
        if status == "done":
            return _ok({
                "status": "done",
                "spec_key": row["spec_key"],
                "entry_status": row["result"]["status"],
            })
        # status == "error"
        return _ok({"status": "error", "error": row["result"]["error"]})
